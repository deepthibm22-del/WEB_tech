//assignment operator

// simple assignment (=)
let a=10
console.log(a);//10

// addition assignment (+=)
let b=10
b+=5
console.log(b);//15

// // subtraction assignment (-=)
let c=10
c-=5
console.log(c);//5


// // multiplication assignment (*=)
let d=10
d*=5
console.log(d);//50

// // division assignment (/=)
let e=10
e/=5
console.log(e);//2

// // modulus assignment (%=)
let g=10
g%=5
console.log(g);//0
